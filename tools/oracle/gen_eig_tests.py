"""Generates src/NDSharp.Tests/EigCases.g.cs: matrices and the eigenvalues numpy.linalg.eig computes for them.

The eigenvalue ORDER is not specified (LAPACK's depends on its deflation order), so the tests match computed against
expected values by nearest neighbour; eigenvectors are checked through the residual A v = lambda v, never against numpy's
(they are only defined up to a phase). Run with any Python that has numpy:

    python tools/oracle/gen_eig_tests.py
"""
import numpy as np, os

here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.normpath(os.path.join(here, "..", "..", "src", "NDSharp.Tests", "EigCases.g.cs"))
rng = np.random.default_rng(12345)

def rand_orth(n):
    q, _ = np.linalg.qr(rng.standard_normal((n, n)))
    return q

cases = []  # (name, array, tolerance)
def add(name, a, tol=1e-9):
    cases.append((name, np.asarray(a), tol))

add("identity3", np.eye(3))
add("zeros4", np.zeros((4, 4)))
add("diagonal", np.diag([3.0, -1.0, 0.5, 7.0]))
add("upper_triangular", np.triu(rng.standard_normal((5, 5))))
add("lower_triangular", np.tril(rng.standard_normal((5, 5))))
add("rotation90", [[0.0, -1.0], [1.0, 0.0]])
add("rotation_scaled", [[1.0, -5.0], [5.0, 1.0]])
add("two_by_two", [[1.0, 2.0], [3.0, 4.0]])
add("one_by_one", [[4.25]])
add("jordan3_defective", [[2.0, 1.0, 0.0], [0.0, 2.0, 1.0], [0.0, 0.0, 2.0]], 1e-4)
add("nilpotent4", np.triu(np.ones((4, 4)), 1), 1e-2)
add("cyclic_permutation5", np.roll(np.eye(5), 1, axis=0))
def companion(roots):
    c = np.poly(roots)                    # monic polynomial coefficients
    m = np.diag(np.ones(len(roots) - 1), -1)
    m[0, :] = -c[1:] / c[0]
    return m
add("companion_roots_1_to_5", companion([1, 2, 3, 4, 5]), 1e-7)
add("hilbert6", 1.0 / (np.arange(6)[:, None] + np.arange(6)[None, :] + 1), 1e-9)
add("badly_scaled", [[1.0, 1e8], [1e-8, 1.0]], 1e-6)
q = rand_orth(4)
add("symmetric_repeated_eigenvalue", q @ np.diag([1.0, 1.0, 2.0, 2.0]) @ q.T)
add("block_real_and_complex", np.block([[np.array([[0.0, -2.0], [2.0, 0.0]]), np.zeros((2, 2))],
                                        [np.zeros((2, 2)), np.array([[3.0, 0.0], [0.0, -4.0]])]]))
add("hessenberg6", np.triu(rng.standard_normal((6, 6)), -1))
for n in (3, 4, 5, 8, 15, 30):
    add(f"random_real_{n}", rng.standard_normal((n, n)), 1e-8)
for n in (3, 5, 10):
    add(f"random_complex_{n}", rng.standard_normal((n, n)) + 1j * rng.standard_normal((n, n)), 1e-8)
add("stack_3_4_4", rng.standard_normal((3, 4, 4)), 1e-9)
add("stack_complex_2_3_3", rng.standard_normal((2, 3, 3)) + 1j * rng.standard_normal((2, 3, 3)), 1e-9)

def lit(x):
    return repr(float(x))

lines = [f"// <auto-generated> by tools/oracle/gen_eig_tests.py — do not edit. Expected eigenvalues are numpy {np.__version__}'s numpy.linalg.eig.",
         "namespace NDSharp.Tests;", "",
         "public static class EigCases", "{",
         "    /// <summary>Data is row-major (real parts, then imaginary parts when Complex); Expected* hold every matrix's eigenvalues in numpy's order.</summary>",
         "    public sealed record Case(string Name, int[] Shape, bool Complex, double[] Re, double[] Im, double[] ExpRe, double[] ExpIm, double Tol);", "",
         "    public static readonly Case[] All =", "    {"]
for name, a, tol in cases:
    w = np.linalg.eig(a)[0]
    cx = np.iscomplexobj(a)
    re = ", ".join(lit(x) for x in a.real.ravel())
    im = ", ".join(lit(x) for x in a.imag.ravel()) if cx else ""
    wre = ", ".join(lit(x) for x in w.real.ravel())
    wim = ", ".join(lit(x) for x in w.imag.ravel())
    shape = ", ".join(str(s) for s in a.shape)
    lines.append(f'        new("{name}", new[] {{ {shape} }}, {str(cx).lower()}, new[] {{ {re} }}, new double[] {{ {im} }}, new[] {{ {wre} }}, new[] {{ {wim} }}, {lit(tol)}),')
lines += ["    };", "}", ""]
open(out_path, "w", encoding="utf-8").write("\n".join(lines))
print(f"wrote {out_path}: {len(cases)} cases")


